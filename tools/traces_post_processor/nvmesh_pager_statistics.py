#!/usr/bin/env python3

import sys
import json
import math
import typing
import pprint
import argparse
import collections


class Metric(typing.NamedTuple):
	name: str
	size: int
	count: int
	average: int 

	@property
	def size_count_average(self):
		return (self.size, self.count, self.average)


class Channel(typing.NamedTuple):
	name: str
	first_trace_ts_ns: int
	last_trace_ts_ns: int
	count_system_trace: int
	TRACES: list[Metric]
	TOKENS: list[Metric]
	FUNCTIONS: list[Metric]
	FILES: list[Metric]

	@property
	def empty(self) -> bool:
		return self.first_trace_ts_ns == 0 \
				and self.last_trace_ts_ns == 0 \
				and self.count_system_trace == 0 \
				and bool(self.TRACES) == False \
				and bool(self.TOKENS) == False \
				and bool(self.FUNCTIONS) == False \
				and bool(self.FILES) == False

	@property
	def metrics(self) -> tuple[list[Metric]]:
		return (self.TRACES, self.TOKENS, self.FUNCTIONS, self.FILES)

