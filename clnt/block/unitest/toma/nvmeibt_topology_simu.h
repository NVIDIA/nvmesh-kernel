struct tTopoOfRaid0Chunk{  								// Toma topology of RaidX+0 (10, 40, 50, 60 : stripped array of protection raids)
	int stripeWidth;									// Amount of 'tTopoOfPraidSegment'. Raid1 has stripeWidth=1, 2-mirroring, bunch of disks has width-1 1-mirroring
	struct tTopoOfPraid *raids;							// Array of raid1's.
};

struct tTopoOfVolume{  									// Toma topology (state of the configuration) of block device / a signle volume
	int nChunks;										// Amount of 'chunks'
	struct tTopoOfRaid0Chunk *chunks;					// Array of chunks's.
	u64 reservation_version;							// Reservation version given by client if > toma update toma to client and return toma, if client == -1 ignore and return toma
	int	version;										// Each time management updates the volume this number grows
	const struct disk_range *segs;						// Original configuration comming from the management mongo-db. Toma cannot change it
	int n_segs;											// Amount of segments in the volume (sum of all segments in all raind1's)
	const char* uuid;									// UUID of volume, from original configuration comming from the management. Toma cannot change it
	const struct nvmeibc_locks_scheme_conf*locks_scheme;// How client, does the locking. Pointer to mongo-db simulator
};
void tTopoOfVolume_destroy(	  struct tTopoOfVolume* V);	// Destructor
void tTopoOfVolume_incVer(	  struct tTopoOfVolume* V);	// Increase the version of all raid1s in the volume. As If client was down and missed updated tomas topologies on all the segments
bool tTopoOfVolume_isMirrored(const struct tTopoOfVolume* V);	// True if Raid1 or 10, False for Raid0 or Jbod
bool tTopoOfVolume_isStriped( const struct tTopoOfVolume* V);	// True if Raid0 or 10, False for Raid1 or Jbod
struct tTopoOfPraid* tTopoOfVolume_getRaid1(struct tTopoOfVolume* V, int i);	// Get the i'th raid-stripe of the volume (takes into account amount of chunks and stripes). On illegal index returns NULL

struct tTopoOfNVMesh { 									// Global topology of all the system (NVMesh) as generated by Toma leader
	int nVolumes;										// Amount of volumes and thin volumes
	struct tTopoOfVolume vols[MAX_VOLUMES_IN_NVMESH];	// Array  of volumes
	pthread_mutex_t lock;									// Lock to change topology atomically. Todo: make it per-protection-raid
};

