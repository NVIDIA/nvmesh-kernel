const struct tTopoOfPraid* tTopoOfNVMesh_find_r1_by_praid_uuid( const struct tTopoOfNVMesh *gTopo, const char* praid_uuid, const struct tTopoOfVolume **tv_ptr);
     struct tTopoOfVolume* tTopoOfNVMesh_find_carrier_by_uuid(const struct tTopoOfNVMesh *gTopo, const char* vol_uuid);
