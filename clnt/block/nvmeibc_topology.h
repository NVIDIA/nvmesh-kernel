/*
 * A volume has space allocated to it based upon its type (JBOD/LVM, RAID-0,
 * RAID-1, etc.). It may not be possible to allocate all its space in one
 * allocation. Each allocation is called a chunk. A chunk fulfills a range of
 * virtual block addresses on the volume. There is no limit to the number of
 * chunks in a volume. Each chunk requires one or more allocations from
 * different drives (depdending on the volume type). A JBOD / LVM has one
 * allocation per chunk. A RAID-1 has 2. A RAID-0 has stripe width allocations.
 * RAID-10 has 2 * width.
 */
struct nvmeibc_chunk {
    u64 first_vlba;                         // Beginning of the range of virtual block adresses on the volume
	int stripe_size;						// Num of sequential blocks in each stripe. In raid5+0 (D+P), skipping stripe after 1 lock, slice size is 32[blocks]*D. Todo: move to be a field of per chunk
	//int stripe_width;						// 1 If not striped. Amount of elements in the raid1s array. Todo: move this field from topology
	struct nvmeibc_raid1 *raid1s;  			// Array of allocations. Length of the array depends upon type of the volume (read above). If RAID 1, segment 2*i and 2*i+1 are mirrors
    struct nvmeibc_topology *topology;      // References back to the configuration (type of the volume) which holds this chunk. Private struct defined in nvmeibc_topology.h
};
