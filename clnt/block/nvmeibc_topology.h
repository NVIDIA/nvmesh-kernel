/* Data protection raid struct: Supports D+P: 1+{0..3}, {2..8}+{1..2} */
struct nvmeibc_raid1 {
	int version;							// Unique id for multiple segments which mirror each other. Starts from 1 and grows to infinity
	int replicas;							// Number of segments in praid
	int slice_size;							// Size in blocks of a single slice in protection raid, For raid1 it is 1, for raid5 - the amount of D segments. We write exactly one block in each segment in a slice to minimize the amount of parities written
	union nvmeib_lock_id lid;				// Toma Lock id (generated by toma) - written into locks (toma can know which client locked the memory). 0=unlocked value. Unique for each raid1 (in each block device in each client).
	struct {								// Auxiliary fields for toma protocol. Should be private if this was a class. dont access them from outside of topology.c implementation
		u32	topo_checksum;						// Checksum of topology. Must be identical regardless of which toma generates it. Designed to catch bugs where different topo use same praid version
		enum nvmeib_io_type_permission io_perm;	// Use nvmeibc_raid1_get_io_perm() in datapath. This field represents only the permission given by toma, If raid is validly registered this is the maximal permissions it may have
		u64 conversation_ind;				// Latest conversatino id with Tomas on which the current lock id was agreed. Ever growing number
	} toma;
	struct nvmeibc_raid_topo_persistent *hdr; // Persistant header of raid1, not changed with dup_topo()
	struct nvmeibc_disk_segment *segments;  // Array of 'replicas' allocations
	struct nvmeibc_locks_scheme lock_scheme;// Locking scheme is relevant for each protection raid
	struct nvmeibc_raid1_calculated_data calculated_data; // Calculated data for ACTIVE topology. !!!DO NOT ACCESS DIRECTLY, USE HELPER FUNCTION!!! nvmeibc_raid1_get_calculated_data
	bool use_rdma_locks;
};

