/* Given a topology representing a new configuration, calculate diff from the
 * head (of nt) and append the changes to the head (only append changes, do not
 * apply yet). Will be applied in future in hot or warm fashion.
 * hot - continuos IO. warm - stopping IO (unreg all segments, apply and rereg)
 * Example: Append to deprecated segments their replacements, to upgraded or
 * downgraded raid1s special marks, shrink or grow the volume by chunks etc
 * negative error from errno-base.h is returned or 0 on success
 */
int nvmeibc_calc_and_append_conf_diffs(struct nvmeibc_topologies *nt,
		struct nvmeibc_topology *new_conf_t);

/* If the function above failed, we can try to replace the previous topologies
   with the new configuration. This is a very dangerous step which is done
   during volume reboot. This is done in 2 steps (order is crucial):
   1. Activate the new configuration (to prevent volume being without segments)
   2. Inject it into the previous. */
void nvmeibc_topology_force_replace_t_act(struct nvmeibc_topologies *nt,
									  struct nvmeibc_topologies *new_conf_t);
void nvmeibc_topology_force_replace_t_inj(struct nvmeibc_topologies *nt,
									  struct nvmeibc_topologies *new_conf_t);

/* Cleanup to the 2 functions above (release new condiguration). Should be
   called, once regardless if reconfiguration was success or failure*/
