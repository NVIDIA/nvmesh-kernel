/* Describes roles of segments in specific blockset in a given topology, bit [i]
   represents NOT seg[i] but rather the segment which is i'th from slice start
   Assists datapath in with fast calculations and used for unitests */
struct nvmeibc_roles_bmps {
	struct {			  // Raid configuration (identical to all roles), kept here for optimization purposes, even though only a single copy is needed
		roles_bmp_t data; // Example: R6=8+2 .data=0xFF .pari= 0x300, .all=0x3FF/
		roles_bmp_t pari; // Data bits = 0 parity = 1
		roles_bmp_t all;  // Data bits = 1 parity = 1
	} raid;

	sgmnts_bmp_t data_sgmnts;   // Example: R6=8+2, Slice start on seg2 (shift=2). .data_sgmnts = 0x3FC, .pari_sgmnts=0x3
	sgmnts_bmp_t pari_sgmnts;   // Actual parity segments for given shift

	roles_bmp_t rw;				// Topology RW roles
	roles_bmp_t wp;				// Topology W+ roles
	roles_bmp_t w;				// Topology Writeable non readable (W|W-)
	roles_bmp_t wm;				// Topology W- roles
	roles_bmp_t dead;			// Topology dead roles
	roles_bmp_t readable;		// Topology RW | W+ roles: Source can be trusted.
	roles_bmp_t readable_sync;	// == ~(wm|dead). During sync, 'W' can be read, even with dirty bit, just to compare to expected data (avoid unnecessary write). But it is not a valid source of data only if dbit does not exist

	roles_bmp_t dbits_off_mask; // == .w,    A bitmap representing a set of roles writing to which may turn off dirty bits
	roles_bmp_t dbits_on_mask;  // == .dead, A bitmap representing a set of roles writing to which may turn on  dirty bits

	roles_bmp_t local_access;	// Roles for segments residing on disks where access is local

	// Flags
	u16 has_protection    :1;   // hweight32(dead|write) < protection ( == (replicas - slice size) == pari)
	u16 has_rw_pari       :1;   // (rw & pari) != 0
	u16 has_writable_pari :1;   // (~bmps.dead & bmps.pari) != 0
	u16 reserved         :13;
}__attribute__((packed));

void nvmeibc_raid1_acm2bmp(enum NVMEIBTC_DS_MODE acm, int si, struct nvmeibc_roles_bmps *bmp);

static inline void nvmeibc_update_roles_bmps_flags(struct nvmeibc_roles_bmps* bmps) {
	bmps->has_protection = hweight32(bmps->dead|bmps->w) < hweight32(bmps->raid.pari);
	bmps->has_rw_pari = (0 != ((bmps->rw | bmps->wp) & bmps->raid.pari));
	bmps->has_writable_pari = ((bmps->dead & bmps->raid.pari) != bmps->raid.pari);
	bmps->reserved = 0;
}

