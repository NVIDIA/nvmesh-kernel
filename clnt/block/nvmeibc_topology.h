/* This object exist per core BUT unlike percpu all cores update it regularly.*/
struct topo_percore_shared {				// It must *NOT* be within the percpu pages bcz otherwise it will cause contention for other variables that share the cache line & assume that the data is private for the core.
	spinlock_t 		list_access;			// Accessing the list below: 1 cpu adds new io's  while another cpu removes when it finishes previous io
	struct list_head	io_wait_list;		// list of IO's waiting for execution (kernel sent those io to this cpu so they are in its list)
	u64				ios_completed;			// # of in air io's (originating from this core) that were already completed (by this or other core), monotonically increasing.
	struct nvmeibc_io_throttle_metrics throttle_metrics;
	int 			n_wait_list;			// number of 'op' queued in the wait-list
	#ifdef DEBUG_PERCPU_ISSUED_IO_CNTRS
		unsigned	n_ios;					// # of io's that are currently in-flight from this core (debugging counter only) == (ios_issued - ios_completed).
	#endif
} ____cacheline_aligned;

struct topos_percpu {						// This object has member that each core maintains seperately
	volatile int nt_users; /* Amount or topo-readers (doing get() put() topo). 0 or 1 for each CPU */
	unsigned long flags;	 /* Obtaining topology must be with irq disabled */
	u64		ios_issued;						// # of io's in air (originating from this core) that were issued, monotonically increasing.
} ____cacheline_aligned;

enum nvmeibc_topo_boot_state {						// Internal boot state of the topologies, used during volume reboot/detach/suspend/revive operations
	NVMEIBC_TOPO_BOOT_NORMAL			= 0x0,		// Reboot not running. Must be zero!
	NVMEIBC_TOPO_BOOT_SUSPENDING		= 0x2,		// Entered suspend attempt, waiting too drain all topos before the suspended one.
	NVMEIBC_TOPO_BOOT_LIST_CLEANUP		= 0x3,		// Cleaning up topos list (unregister, unsubscribe segments), soon the list will be empty
	NVMEIBC_TOPO_BOOT_NO_GET_TOPO		= 0x4,		// List cannot support get() operations, it might be empty now or last topo is being freed
	NVMEIBC_TOPO_BOOT_APPLIED_NEW		= 0x5,		// New configuration is inserted as starting topology
	NVMEIBC_TOPO_BOOT_REVIVING			= 0x6,		// Registering segments of new topology. Will soon transition back to Normal
};
#define is_suspended(nt) (((nt).boot_state!=NVMEIBC_TOPO_BOOT_NORMAL))


